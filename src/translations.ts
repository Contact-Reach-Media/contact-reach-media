/**
 * Returns the localized category title for any category object or category identifier
 */
export function getCategoryTitle(
  category: { id?: string; nameEn?: string; nameRw?: string } | string,
  lang: Language
): string {
  if (!category) return '';
  const catId = typeof category === 'string' ? category : (category.id || '');
  const normalizedKey = catId.toLowerCase().trim();

  if (CATEGORY_TRANSLATIONS[normalizedKey] && CATEGORY_TRANSLATIONS[normalizedKey][lang]) {
    return CATEGORY_TRANSLATIONS[normalizedKey][lang];
  }

  // Fallback to nameEn or nameRw if object provided
  if (typeof category === 'object') {
    if (lang === 'rw' && category.nameRw) return category.nameRw;
    if (category.nameEn) return category.nameEn;
  }

  // Fallback to capitalize string
  return catId ? catId.charAt(0).toUpperCase() + catId.slice(1) : '';
}
